"""Fetch the latest posts from the Substack RSS feed into _data/substack.yml.

Run by .github/workflows/substack.yml once a day. Standard library only.
Only rewrites the file when the posts change, so the workflow can skip empty commits.
"""
import json, re, sys, urllib.request, xml.etree.ElementTree as ET
from email.utils import parsedate_to_datetime

FEED = "https://melvinjoseuae.substack.com/feed"
OUT = "_data/substack.yml"
LIMIT = 6
EXCLUDE = {"welcome-to-the-uae-ledger"}  # post slugs to leave off the site

HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36",
    "Accept": "application/rss+xml, application/xml;q=0.9, */*;q=0.8",
    "Accept-Language": "en-GB,en;q=0.9",
}
req = urllib.request.Request(FEED, headers=HEADERS)
root = ET.fromstring(urllib.request.urlopen(req, timeout=30).read())

posts = []
for it in root.iter("item"):
    link = (it.findtext("link") or "").strip()
    slug = link.rstrip("/").rsplit("/", 1)[-1]
    if not link or slug in EXCLUDE:
        continue
    enc = it.find("enclosure")
    excerpt = re.sub(r"<[^>]+>", "", it.findtext("description") or "").strip()
    posts.append({
        "title": (it.findtext("title") or "").strip(),
        "url": link,
        "date": parsedate_to_datetime(it.findtext("pubDate")).strftime("%Y-%m-%d"),
        "excerpt": excerpt[:280],
        "image": enc.get("url") if enc is not None and (enc.get("type") or "").startswith("image") else "",
    })
    if len(posts) >= LIMIT:
        break

# YAML is a superset of JSON, so JSON-quoted values are valid and safe.
body = "# Generated by scripts/fetch_substack.py. Do not edit by hand.\n" + (
    "".join("- " + "\n  ".join(f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in p.items()) + "\n" for p in posts) or "[]\n")
try:
    old = open(OUT, encoding="utf-8").read()
except FileNotFoundError:
    old = ""
if old != body:
    open(OUT, "w", encoding="utf-8").write(body)
    print(f"updated: {len(posts)} posts")
else:
    print("no change")
